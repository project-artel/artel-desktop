import path from 'node:path';

export interface ShimNames {
  /** Executable inside `Contents/MacOS` on macOS. */
  macExecutable: string;
  /** Executable next to `resources` on Linux. */
  linuxExecutable: string;
  /** Executable next to `resources` on Windows. */
  windowsExecutable: string;
}

export const DEFAULT_SHIM_NAMES: ShimNames = {
  macExecutable: 'ARTEL',
  linuxExecutable: 'artel-desktop',
  windowsExecutable: 'artel.exe',
};

const CLI_RELATIVE = [
  'app.asar.unpacked',
  'node_modules',
  '@project-artel',
  'cli',
  'dist',
  'cli.js',
];

/** `bin/artel` for macOS and Linux. Follows symlinks, so `/usr/bin/artel` works. */
export function shimSh(names: ShimNames = DEFAULT_SHIM_NAMES): string {
  return `#!/bin/sh
# Generated by scripts/write-shims.mjs. Runs the ARTEL command line with the desktop app's own Node.
src="$0"
while [ -h "$src" ]; do
  dir=$(cd -P "$(dirname "$src")" && pwd)
  src=$(readlink "$src")
  case "$src" in
    /*) ;;
    *) src="$dir/$src" ;;
  esac
done
resources=$(cd -P "$(dirname "$src")/.." && pwd)
if [ -x "$resources/../MacOS/${names.macExecutable}" ]; then
  app="$resources/../MacOS/${names.macExecutable}"
else
  app="$resources/../${names.linuxExecutable}"
fi
ELECTRON_RUN_AS_NODE=1 ARTEL_RUNTIME_DIR="$resources/runtime" exec "$app" "$resources/${CLI_RELATIVE.join('/')}" "$@"
`;
}

/** `bin/artel.cmd` for Windows. */
export function shimCmd(names: ShimNames = DEFAULT_SHIM_NAMES): string {
  const lines = [
    '@echo off',
    "rem Generated by scripts/write-shims.mjs. Runs the ARTEL command line with the desktop app's own Node.",
    'setlocal',
    'set "RESOURCES=%~dp0.."',
    'set "ELECTRON_RUN_AS_NODE=1"',
    'set "ARTEL_RUNTIME_DIR=%RESOURCES%\\runtime"',
    `"%RESOURCES%\\..\\${names.windowsExecutable}" "%RESOURCES%\\${CLI_RELATIVE.join('\\')}" %*`,
    'exit /b %ERRORLEVEL%',
    '',
  ];
  return lines.join('\r\n');
}

/** Directory holding the shims inside an installed app. */
export function shimDir(resourcesPath: string): string {
  return path.join(resourcesPath, 'bin');
}

/** True when `dir` is already one of the entries in a PATH string. */
export function pathContains(pathValue: string, dir: string, platform: NodeJS.Platform): boolean {
  const separator = platform === 'win32' ? ';' : ':';
  const normalize = (entry: string): string => {
    const trimmed = entry.length > 1 ? entry.replace(/[\\/]+$/, '') : entry;
    return platform === 'win32' ? trimmed.toLowerCase() : trimmed;
  };
  const wanted = normalize(dir);
  return pathValue
    .split(separator)
    .filter((entry) => entry !== '')
    .some((entry) => normalize(entry) === wanted);
}

/** New user PATH value with `dir` appended once. Used for Windows, `;` separated. */
export function addToPath(pathValue: string, dir: string): string {
  if (pathContains(pathValue, dir, 'win32')) return pathValue;
  const entries = pathValue.split(';').filter((entry) => entry !== '');
  return [...entries, dir].join(';');
}

/** New user PATH value without `dir`. Used for Windows, `;` separated. */
export function removeFromPath(pathValue: string, dir: string): string {
  const entries = pathValue.split(';').filter((entry) => entry !== '');
  return entries.filter((entry) => !pathContains(entry, dir, 'win32')).join(';');
}

export interface CliLinkPlan {
  kind: 'none' | 'symlink-admin' | 'script-user';
  /** Where the `artel` command is placed. */
  linkPath?: string;
  /** What it points to: the shim for `symlink-admin`, the AppImage for `script-user`. */
  targetPath?: string;
  /** True when `linkPath` is not in `PATH`, so the user must add its directory. */
  needsPathHint?: boolean;
}

export interface CliLinkInput {
  platform: NodeJS.Platform;
  resourcesPath: string;
  homeDir: string;
  /** `process.env.APPIMAGE`, set when running from an AppImage. */
  appImage?: string | undefined;
  pathEnv: string;
}

/**
 * What the app can offer to put `artel` on PATH after install:
 * macOS links `/usr/local/bin/artel` (administrator prompt), an AppImage writes a launcher
 * script into `~/.local/bin`. Windows (NSIS) and Linux deb do it in the installer.
 */
export function planCliLink(input: CliLinkInput): CliLinkPlan {
  if (input.platform === 'darwin') {
    return {
      kind: 'symlink-admin',
      linkPath: '/usr/local/bin/artel',
      targetPath: path.posix.join(input.resourcesPath, 'bin', 'artel'),
    };
  }
  if (input.platform === 'linux' && input.appImage !== undefined && input.appImage !== '') {
    const binDir = path.posix.join(input.homeDir, '.local', 'bin');
    return {
      kind: 'script-user',
      linkPath: path.posix.join(binDir, 'artel'),
      targetPath: input.appImage,
      needsPathHint: !pathContains(input.pathEnv, binDir, 'linux'),
    };
  }
  return { kind: 'none' };
}

/** Single-quote a string for `sh`. */
export function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** The `osascript` arguments that link the shim with an administrator prompt. */
export function macLinkOsascriptArgs(plan: CliLinkPlan): string[] {
  if (plan.linkPath === undefined || plan.targetPath === undefined) {
    throw new Error('plan has no link path');
  }
  const shell = `mkdir -p ${shQuote(path.posix.dirname(plan.linkPath))} && ln -sf ${shQuote(plan.targetPath)} ${shQuote(plan.linkPath)}`;
  const escaped = shell.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return ['-e', `do shell script "${escaped}" with administrator privileges`];
}

/**
 * Launcher for an AppImage. Electron stops reading its own switches after `--`, so
 * `artel --version` reaches the CLI instead of Electron's version output.
 */
export function appImageLauncher(appImagePath: string): string {
  return `#!/bin/sh
# Written by ARTEL Desktop. Runs the ARTEL command line from the AppImage.
ARTEL_RUN_CLI=1 exec ${shQuote(appImagePath)} -- "$@"
`;
}

/** Arguments for the CLI when the app was started in `ARTEL_RUN_CLI` mode. */
export function cliArgsFromArgv(argv: readonly string[]): string[] {
  const separator = argv.indexOf('--');
  return separator === -1 ? [] : argv.slice(separator + 1);
}
